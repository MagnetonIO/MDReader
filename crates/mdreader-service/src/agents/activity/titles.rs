//! Prompt-derived titles: the first real user prompt, shortened. Commands,
//! injected context blocks and paste markers are skipped. Nothing else from
//! a prompt is retained.

const MAX_CHARS: usize = 60;

fn is_marker(word: &str) -> bool {
    word.starts_with("[Pasted") || word.starts_with("[Image") || word.starts_with("[File")
}

/// Strip `[Pasted text #1 +20 lines]`-style markers from a line.
fn without_markers(line: &str) -> String {
    let mut out = String::new();
    let mut rest = line;
    while let Some(start) = rest.find('[') {
        let (before, tail) = rest.split_at(start);
        out.push_str(before);
        match tail.find(']') {
            Some(end) if is_marker(&tail[..end]) => rest = &tail[end + 1..],
            _ => {
                out.push('[');
                rest = &tail[1..];
            }
        }
    }
    out.push_str(rest);
    out
}

/// A title from a user prompt, or `None` when the prompt is not a real one.
pub(super) fn prompt_title(text: &str) -> Option<String> {
    let text = text.trim_start();
    if text.starts_with('/')
        || text.starts_with('<')
        || text.starts_with("Caveat:")
        || text.starts_with('!')
    {
        return None;
    }
    let line = text
        .lines()
        .map(without_markers)
        .map(|l| l.split_whitespace().collect::<Vec<_>>().join(" "))
        .find(|l| !l.is_empty() && !l.starts_with("```"))?;
    if line.chars().count() < 3 {
        return None;
    }
    if line.chars().count() <= MAX_CHARS {
        return Some(line);
    }
    let cut: String = line.chars().take(MAX_CHARS).collect();
    let cut = match cut.rfind(' ') {
        Some(space) if space >= MAX_CHARS / 2 => &cut[..space],
        _ => cut.as_str(),
    };
    Some(format!(
        "{}…",
        cut.trim_end_matches([' ', ',', '.', ':', ';'])
    ))
}

#[cfg(test)]
mod tests {
    use super::prompt_title;
    #[test]
    fn real_prompts_become_short_titles() {
        assert_eq!(
            prompt_title("  Fix the CI desktop e2e job\nmore detail").as_deref(),
            Some("Fix the CI desktop e2e job")
        );
        assert_eq!(prompt_title("/clear"), None);
        assert_eq!(prompt_title("<command-name>/model</command-name>"), None);
        assert_eq!(prompt_title("Caveat: generated by a local command"), None);
        assert_eq!(
            prompt_title("[Pasted text #1 +20 lines] summarize this").as_deref(),
            Some("summarize this")
        );
        assert_eq!(prompt_title("[Pasted text #1 +20 lines]"), None);
        assert_eq!(
            prompt_title("keep [brackets] intact").as_deref(),
            Some("keep [brackets] intact")
        );
        let long = prompt_title(
            "Please refactor the synthetic settings sheet so that every toggle is keyboard accessible",
        )
        .unwrap();
        assert!(long.ends_with('…') && long.chars().count() <= 61, "{long}");
        assert!(long.starts_with("Please refactor the synthetic settings sheet"));
    }
}
