import { act, cleanup, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, expect, test, vi } from 'vitest';
import { saveDraftCopy } from '../document-transfer/draft-copy';
import { beginDeviceEdit, useDeviceEdits } from '../device-editing/store';
import { DeviceEditor } from '../device-editing/DeviceEditor';
import { ProviderEditor } from '../provider-editing/ProviderEditor';
import { beginProviderEdit, useProviderEdits } from '../provider-editing/store';
import { providerEditBackend } from '../provider-editing/backend';
import { useEditorStore } from '../../stores/editor';
vi.mock('../document-transfer/draft-copy', () => ({ saveDraftCopy: vi.fn() }));
vi.mock('../../shell/SourcePane', () => ({ SourcePane: () => <div /> }));
vi.mock('../provider-editing/backend', () => ({ providerEditBackend: { begin: vi.fn() } }));
afterEach(() => { cleanup(); vi.resetAllMocks(); useEditorStore.getState().reset(); useDeviceEdits.setState({ edits: {} }); useProviderEdits.setState({ edits: {} }); });
test('device copy cancellation preserves a dirty buffer and does not publish its edit', async () => {
  const reference = { documentId: '11111111-1111-4111-8111-111111111111', sourceId: 'a'.repeat(64), path: 'document.md', revision: 'b'.repeat(64), title: 'Original.md' };
  const backend = { read: vi.fn(async () => ({ ...reference, operation: 'read_document' as const, markdown: '# Original', lineStart: 1, lineEnd: 1 })), save: vi.fn(), manifest: vi.fn(), images: vi.fn() };
  const key = (await beginDeviceEdit('reader:tab', reference, () => true, backend))!;
  useEditorStore.getState().edit('reader:tab', key, '# Unsaved');
  vi.mocked(saveDraftCopy).mockResolvedValue('cancelled');
  const published = vi.fn(); render(<DeviceEditor editKey={key} onRead={vi.fn()} onPublished={published} />);
  await act(async () => fireEvent.click(screen.getByRole('button', { name: 'Save a copy…' })));
  expect(useEditorStore.getState().entry('reader:tab', key)).toMatchObject({ buffer: '# Unsaved', savedContent: '# Original', dirty: true });
  expect(saveDraftCopy).toHaveBeenCalledExactlyOnceWith('# Unsaved', 'Original.md');
  expect(backend.save).not.toHaveBeenCalled(); expect(published).not.toHaveBeenCalled();
  expect(screen.getByText('Copy not saved. Your editor draft is kept.')).toBeTruthy();
});
test('provider conflict still allows preservation and an export failure retains uncertain state', async () => {
  const reference = { sourceId: `provider:${'a'.repeat(64)}`, path: `records/${'b'.repeat(64)}.md`, revision: 'c'.repeat(64), title: 'Cloud note.md' };
  vi.mocked(providerEditBackend.begin).mockResolvedValue({ operation: 'begin_edit_exact', editId: 'native-edit', writeSourceId: 'opaque', markdown: '# Original', expiresAtMs: 1, projection: { jobId: 'job', readerSourceId: reference.sourceId, path: reference.path, revision: reference.revision } });
  const key = (await beginProviderEdit('reader:tab', reference, () => true))!;
  useEditorStore.getState().edit('reader:tab', key, '# Kept after conflict');
  useProviderEdits.getState().update(key, { phase: 'conflict', pendingBody: '# Previously sent' });
  vi.mocked(saveDraftCopy).mockRejectedValue(new Error('Copy write unconfirmed.'));
  render(<ProviderEditor editKey={key} onRead={vi.fn()} onPublished={vi.fn()} />);
  await act(async () => fireEvent.click(screen.getByRole('button', { name: 'Save a copy…' })));
  expect(saveDraftCopy).toHaveBeenCalledExactlyOnceWith('# Kept after conflict', 'Cloud note.md');
  expect(useProviderEdits.getState().edits[key]).toMatchObject({ phase: 'conflict', pendingBody: '# Previously sent' });
  expect(useEditorStore.getState().entry('reader:tab', key)).toMatchObject({ buffer: '# Kept after conflict', dirty: true });
  expect(screen.getByRole('alert').textContent).toBe('Copy write unconfirmed.');
});
